#Requires -Version 7
<#
.SYNOPSIS
    Gate: a change adds no dead or noisy comment to C#, Razor, PowerShell or YAML (clause C10).
.DESCRIPTION
    -Language picks the files it reads. CSharp, the default, reads .cs and .razor files, and the
    core gates.json runs it as a Blocking gate. YamlPowerShell reads .ps1, .psm1, .psd1, .yml and .yaml
    files, and runs as an Advisory gate, so a finding there never stops a push. Both modes apply the
    same C10 checks; only the way a comment is found differs.

    Code is documented, and a comment says why, not what. Three kinds of comment never help, so this
    gate reports them in the lines a change adds:
      - commented-out code: a comment whose text reads as a statement or declaration. In C# it ends
        with ;, { or }, or it starts like code: var x =, return x(, if (, foreach (, public int X {, [Fact];
        in PowerShell and YAML it reads like $x = 1, Get-Item -Path $p, if (...) {, - uses: or key: "value";
      - a TODO, FIXME or HACK without an issue key, such as #42 (tracker.keyPattern in aisdlc.json);
      - a comment that names an AI tool: Claude, Copilot, ChatGPT, GPT, "generated by" or "AI-generated".
    A /// doc comment is not read as code, but the other two checks apply to it. The // Arrange, // Act
    and // Assert test markers pass. See the comments page of the ai-sdlc-handbook skill
    (.claude/skills/ai-sdlc-handbook/references/comments.md).

    The gate reads the change, not the tree: only ADDED lines are checked, so old comments do not fail
    anyone. The diff carries 30 lines of context, and those lines are read too, so an added line inside
    a raw string or a /* */ block that opened just before the change is judged by what it really is.
    It diffs the working tree against the merge base of -BaseRef and HEAD, and it reads untracked .cs
    and .razor files whole.

    What counts as a comment:
      C#     a line that starts with //, /// or /*, a line inside a /* */ block, and a trailing // or
             /* after code. String and character literals are removed first, including raw ("""),
             verbatim (@", $@", @$") and interpolated strings, so a URL inside a string is not a comment.
      Razor  the C# forms above at the start of a line, a @* *@ block and an <!-- --> block.
    Known limit: a string or a block that opened more than 30 lines before the change is not seen.
    Generated files (*.Designer.cs, *.g.cs, *.g.i.cs and anything under bin/ or obj/) are skipped.

    What counts as a comment in YamlPowerShell mode:
      PowerShell  every comment token of the PowerShell parser, so a # inside a string or a here-string
                  is not a comment. The comment-based help block is documentation: its lines pass the code and
                  AI tool checks, because a gate script must name the tools it looks for, but an open
                  task without an issue key is still a finding there. #Requires, #region, #endregion,
                  a shebang and the marker lines ai-sdlc:<package>:start and ai-sdlc:<package>:end pass.
      YAML        a # at the start of a line or after a space, outside a quoted string. A line that
                  starts with # inside a block scalar, such as an inline script, counts too. The same
                  lines pass.
    When git reads the change, a PowerShell or YAML file is read whole from the working tree, so a long
    help block or here-string is judged by what it really is. A PowerShell file that does not parse is
    named as not checked, never passed as clean. The files that apm.lock.yaml lists as installed are
    skipped, because the install wrote them (Get-AiSdlcInstalledPath -WithHeadInstall in
    ChangedFiles.psm1). The gate does not report a new script that has no help block.

    Exit codes follow Invoke-Gate.ps1: 0 checked and clean, 1 a finding, 2 the change could not be
    computed (no git, no repository, or no base ref) or a PowerShell file does not parse, so nothing
    was checked there. In YamlPowerShell mode, 3 means the change adds no line of that language.
.PARAMETER RepoRoot
    Repository root. Defaults to the folder that holds aisdlc.json, found from this script.
.PARAMETER BaseRef
    The ref the change is measured against. Defaults to origin/<github.trunk> from aisdlc.json (Get-AiSdlcMainBranch), origin/main unless the repository names another trunk. The pull request build passes
    HEAD^1, the target branch side of the merge commit.
.PARAMETER DiffText
    A unified diff to read instead of asking git. Used by the tests.
.PARAMETER Language
    CSharp (the default) or YamlPowerShell: the files the check reads. See the description.
.EXAMPLE
    pwsh .claude/skills/ai-sdlc-gates/scripts/Check-CommentHygiene.ps1
.EXAMPLE
    pwsh .claude/skills/ai-sdlc-gates/scripts/Check-CommentHygiene.ps1 -Language YamlPowerShell
.EXAMPLE
    pwsh .claude/skills/ai-sdlc-gates/scripts/Check-CommentHygiene.ps1 -BaseRef HEAD^1
#>
[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$BaseRef,
    [string]$DiffText,
    [ValidateSet('CSharp', 'YamlPowerShell')]
    [string]$Language = 'CSharp'
)

Import-Module (Join-Path $PSScriptRoot 'AiSdlcConfig.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'ChangedFiles.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'CodeDiff.psm1') -Force
if (-not $RepoRoot) { $RepoRoot = Find-AiSdlcRepoRoot -StartPath $PSScriptRoot }
if (-not $BaseRef) { $BaseRef = Get-AiSdlcMainBranch -RepoRoot $RepoRoot }

$ErrorActionPreference = 'Stop'

$testMarker = '^//\s*(Arrange|Act|Assert)(\s*(&|and|/|,)\s*(Arrange|Act|Assert))*\s*$'
$literalPattern = '\$*(?<q>"{3,})(?:(?!\k<q>).)*\k<q>|(?:\$@|@\$|@)"(?:[^"]|"")*"|\$"(?:[^"\\{}]|\\.|\{\{|\}\}|\{(?:[^{}"]|"(?:[^"\\]|\\.)*")*\})*"|\$?"(?:[^"\\]|\\.)*"|''(?:[^''\\]|\\.)'''
$aiToolPattern = '(?i)\b(claude|copilot|chatgpt|gpt)\b|\bgenerated\s+by\b|\bai[- ]generated\b'
$todoPattern = '(?-i)\b(TODO|FIXME|HACK)\b'
$codeStartPatterns = @(
    '^(if|for|foreach|while|switch|using|lock|catch)\s*\(',
    '^var\s+\w+\s*=',
    '^(return|throw|await|yield\s+return)\s+(new\s+)?[\w.<>\[\]]+\s*[\(;]',
    '^(public|private|protected|internal)\s+([\w<>\[\],?]+\s+)+\w+\s*(\(|\{|=|;)',
    '^\[\w+(\(.*\))?\]$'
)

function Remove-Literals {
    param([string]$Line)
    [regex]::Replace($Line, $literalPattern, '""')
}

function Split-OpenString {
    param([string]$Code)
    $raw = [regex]::Match($Code, '(?<q>"{3,})\s*$')
    if ($raw.Success) { return [pscustomobject]@{ Before = $Code.Substring(0, $raw.Index); End = $raw.Groups['q'].Value } }
    $verbatim = [regex]::Match($Code, '(?:\$@|@\$|@)"')
    if ($verbatim.Success) { return [pscustomobject]@{ Before = $Code.Substring(0, $verbatim.Index); End = 'verbatim' } }
    return [pscustomobject]@{ Before = $Code; End = $null }
}

function Close-OpenString {
    param([string]$Text, [string]$End)
    $close = if ($End -eq 'verbatim') { [regex]::Match(($Text -replace '""', '__'), '"') } else { [regex]::Match($Text, [regex]::Escape($End)) }
    if (-not $close.Success) { return $null }
    return $Text.Substring($close.Index + $close.Length).Trim()
}

function Get-TrailingComment {
    param([string]$Text, [hashtable]$State)
    $open = Split-OpenString (Remove-Literals $Text)
    $State.StringEnd = $open.End
    $trailing = [regex]::Match($open.Before, '//|/\*')
    if (-not $trailing.Success) { return $null }
    $rest = $open.Before.Substring($trailing.Index)
    if ($trailing.Value -eq '/*' -and -not $rest.Substring(2).Contains('*/')) { $State.BlockEnd = '*/' }
    return $rest
}

function Get-LeadingComment {
    param([string]$Text, [bool]$IsRazor, [hashtable]$State)
    if ($IsRazor) {
        $razorOpen = [regex]::Match($Text, '@\*|<!--')
        if ($razorOpen.Success) {
            $close = if ($razorOpen.Value -eq '@*') { '*@' } else { '-->' }
            if (-not $Text.Substring($razorOpen.Index + $razorOpen.Length).Contains($close)) { $State.BlockEnd = $close }
            return $Text.Substring($razorOpen.Index)
        }
    }
    if ($Text.StartsWith('//')) { return $Text }
    if ($Text.StartsWith('/*')) {
        if (-not $Text.Substring(2).Contains('*/')) { $State.BlockEnd = '*/' }
        return $Text
    }
    return $null
}

function Get-CommentText {
    param([string]$Text, [bool]$IsRazor, [hashtable]$State)
    if ($State.StringEnd) {
        $rest = Close-OpenString -Text $Text -End $State.StringEnd
        if ($null -eq $rest) { return $null }
        $State.StringEnd = $null
        if ($rest -eq '') { return $null }
        return (Get-TrailingComment -Text $rest -State $State)
    }
    if ($State.BlockEnd) {
        if ($Text.Contains($State.BlockEnd)) { $State.BlockEnd = $null }
        return $Text
    }
    if ($Text -eq '') { return $null }
    $leading = Get-LeadingComment -Text $Text -IsRazor $IsRazor -State $State
    if ($null -ne $leading) { return $leading }
    if ($IsRazor) { return $null }
    return (Get-TrailingComment -Text $Text -State $State)
}

function Get-CommentProblem {
    param([string]$Comment)
    if ($Comment -match $testMarker) { return $null }
    if ($Comment -match $aiToolPattern) { return 'names an AI tool' }
    if ($Comment -cmatch $todoPattern -and -not (Get-AiSdlcStoryKey -Text $Comment -RepoRoot $RepoRoot)) { return 'TODO without an issue key' }
    if ($Comment.StartsWith('///')) { return $null }
    $body = ($Comment -replace '^\s*(/{2,}|/\*+|\*+|@\*|<!--)', '' -replace '(\*+/|\*@|-->)\s*$', '').Trim()
    if ($body -eq '') { return $null }
    if ($body -match '[;{}]$' -and $body -notmatch '\S\{[\w:]+\}$') { return 'commented-out code' }
    foreach ($p in $codeStartPatterns) { if ($body -cmatch $p) { return 'commented-out code' } }
    return $null
}

function Find-CommentProblems {
    param([object[]]$Lines)
    $findings = [System.Collections.Generic.List[object]]::new()
    $state = @{ BlockEnd = $null; StringEnd = $null }
    $prev = $null
    foreach ($l in $Lines) {
        $path = $l.File.Replace('\', '/')
        if (-not (Test-CodeDiffPath -Path $path)) { continue }
        if ($prev -and ($prev.File -ne $l.File -or $prev.Line + 1 -ne $l.Line)) { $state.BlockEnd = $null; $state.StringEnd = $null }
        $prev = $l
        $comment = Get-CommentText -Text $l.Text.Trim() -IsRazor $path.EndsWith('.razor') -State $state
        if ($null -eq $comment -or -not $l.IsAdded) { continue }
        $problem = Get-CommentProblem -Comment $comment
        if ($problem) { $findings.Add([pscustomobject]@{ File = $l.File; Line = $l.Line; Text = $l.Text; Problem = $problem }) }
    }
    $findings
}

$scriptPathPattern = '\.(ps1|psm1|psd1|ya?ml)$'
$helpKeyword = '(?im)^\s*\.(SYNOPSIS|DESCRIPTION|PARAMETER|EXAMPLE|INPUTS|OUTPUTS|NOTES|LINK|COMPONENT|ROLE|FUNCTIONALITY|FORWARDHELPTARGETNAME|FORWARDHELPCATEGORY|REMOTEHELPRUNSPACE|EXTERNALHELP)\b'
$allowedLinePattern = '^#(!|requires\b|region\b|endregion\b)|^#\s*ai-sdlc:[\w.-]+:(start|end)\b'
# Prose ends with a full stop; code does not. A sentence that starts with a verb-noun name is not a call.
$powerShellCodePatterns = @(
    '^\$[\w:.{}]+(\[[^\]]*\])*(\.\w+)*\s*([+\-*/]?=)\s*\S',
    '^\$[\w:.]+(\.\w+)*\.\w+\(',
    '^(if|elseif|foreach|for|while|switch|catch)\s*\(',
    '^(try|finally|else|do)\s*\{',
    '^(function|filter)\s+[\w-]+\s*[\{\(]',
    '^param\s*\(',
    '^(return|throw|exit)\s+(\$[\w:.]+|\d+|@[\(\{].*|''.*''|".*")\s*$',
    '^\[[\w.\[\], ]+\]\s*\$\w+',
    '^\[(Parameter|CmdletBinding|ValidateSet|ValidateNotNullOrEmpty|Alias|OutputType)\b.*\]$',
    '^[A-Z][a-z]+-[A-Z]\w+(\s+\S+)*\s+(-[A-Za-z]\w*|\$[\w:]+)(\s|$)',
    '^&\s+[''"$.]',
    '\|\s*([A-Z][a-z]+-[A-Z]\w+|%|\?)(\s|$)'
)
$yamlCodePatterns = @(
    '^-\s+[\w.-]+:(\s|$)',
    '^[\w.-]+:\s+(\$\{\{.*\}\}|"[^"]*"|''[^'']*''|true|false|null|-?\d+(\.\d+)?|\[.*\]|\{.*\})$',
    '^[\w.]*[-_][\w.-]*:\s*$',
    '^[\w.]*[-_][\w.-]*:\s+\S+$',
    '^(steps|jobs|with|env|on|permissions|strategy|matrix|inputs|outputs|runs|needs|services|defaults|dependencies|parameters|variables|stages|pool|resources|extends):\s*$',
    '^\$\{\{.*\}\}$'
)

function Get-ScriptCommentProblem {
    param([string]$Text, [string]$Kind, [bool]$IsYaml)
    if ($Kind -ne 'Help' -and ($Text -replace '\.claude\b', '') -match $aiToolPattern) { return 'names an AI tool' }
    if ($Text -cmatch $todoPattern -and -not (Get-AiSdlcStoryKey -Text $Text -RepoRoot $RepoRoot)) { return 'TODO without an issue key' }
    if ($Kind -eq 'Help') { return $null }
    $body = ($Text -replace '^\s*(<#|#+)', '' -replace '#>\s*$', '').Trim()
    if ($body -eq '') { return $null }
    if ($body -match '[;{}]$' -and $body -notmatch '\S\{[\w:]+\}$') { return 'commented-out code' }
    if ($body.EndsWith('.')) { return $null }
    $patterns = if ($IsYaml) { $powerShellCodePatterns + $yamlCodePatterns } else { $powerShellCodePatterns }
    foreach ($p in $patterns) { if ($body -cmatch $p) { return 'commented-out code' } }
    return $null
}

function Test-HelpBlock {
    param([string]$Text)
    if (-not $Text.StartsWith('<#')) { return $false }
    $first = @(($Text.Substring(2) -replace '#>$', '') -split '\r?\n' | Where-Object { $_.Trim() }) | Select-Object -First 1
    return ([string]$first -match $helpKeyword)
}

function Get-PowerShellComment {
    param([object[]]$Lines, [bool]$WholeFile)
    $last = ($Lines | Measure-Object -Property Line -Maximum).Maximum
    $text = [string[]]::new([int]$last)
    foreach ($l in $Lines) { if ($l.Line -ge 1) { $text[$l.Line - 1] = $l.Text } }
    $tokens = $null
    $parseErrors = $null
    [void][System.Management.Automation.Language.Parser]::ParseInput(($text -join "`n"), [ref]$tokens, [ref]$parseErrors)
    if ($WholeFile -and @($parseErrors).Count -gt 0) { return $null }
    $comments = [System.Collections.Generic.List[object]]::new()
    foreach ($t in @($tokens | Where-Object { $_.Kind -eq 'Comment' })) {
        $isBlock = $t.Text.StartsWith('<#')
        if (-not $isBlock) {
            if ($t.Text -cmatch $allowedLinePattern -or $t.Text -eq '#>') { continue }
            $comments.Add([pscustomobject]@{ Line = $t.Extent.StartLineNumber; Text = $t.Text; Kind = 'Line' })
            continue
        }
        $kind = if (Test-HelpBlock $t.Text) { 'Help' } else { 'Block' }
        $number = $t.Extent.StartLineNumber
        foreach ($part in ($t.Text -split '\r?\n')) {
            $comments.Add([pscustomobject]@{ Line = $number; Text = $part; Kind = $kind })
            $number++
        }
    }
    , $comments
}

function Find-YamlCommentStart {
    param([string]$Text, [hashtable]$State)
    $State.Flow = 0
    for ($i = 0; $i -lt $Text.Length; $i++) {
        $c = $Text[$i]
        if ($State.Quote -eq '"') {
            if ($c -eq '\') { $i++ } elseif ($c -eq '"') { $State.Quote = $null }
            continue
        }
        if ($State.Quote -eq "'") {
            if ($c -eq "'") {
                if ($i + 1 -lt $Text.Length -and $Text[$i + 1] -eq "'") { $i++ } else { $State.Quote = $null }
            }
            continue
        }
        $atStart = $i -eq 0 -or [char]::IsWhiteSpace($Text[$i - 1])
        if ($c -eq '#' -and $atStart) { return $i }
        if ($c -eq '{' -or $c -eq '[') { $State.Flow++ } elseif (($c -eq '}' -or $c -eq ']') -and $State.Flow -gt 0) { $State.Flow-- }
        $opens = $atStart -or '[{,'.Contains([string]$Text[$i - 1]) -or ($State.Flow -gt 0 -and $Text[$i - 1] -eq ':')
        if (($c -eq '"' -or $c -eq "'") -and $opens) { $State.Quote = [string]$c }
    }
    return -1
}

function Get-YamlComment {
    param([object[]]$Lines)
    $comments = [System.Collections.Generic.List[object]]::new()
    $state = @{ Quote = $null; BlockIndent = $null }
    $prev = $null
    foreach ($l in $Lines) {
        if ($null -ne $prev -and $prev + 1 -ne $l.Line) { $state.Quote = $null; $state.BlockIndent = $null }
        $prev = $l.Line
        $text = [string]$l.Text
        $trimmed = $text.Trim()
        $indent = $text.Length - $text.TrimStart().Length
        if ($null -ne $state.BlockIndent) {
            if ($trimmed -eq '' -or $indent -gt $state.BlockIndent) {
                if ($trimmed.StartsWith('#') -and $trimmed -cnotmatch $allowedLinePattern) { $comments.Add([pscustomobject]@{ Line = $l.Line; Text = $trimmed; Kind = 'Line' }) }
                continue
            }
            $state.BlockIndent = $null
        }
        $at = Find-YamlCommentStart -Text $text -State $state
        $code = if ($at -ge 0) { $text.Substring(0, $at) } else { $text }
        if ($at -ge 0) {
            $comment = $text.Substring($at).Trim()
            if ($comment -cnotmatch $allowedLinePattern) { $comments.Add([pscustomobject]@{ Line = $l.Line; Text = $comment; Kind = 'Line' }) }
        }
        if (-not $state.Quote -and $code.TrimEnd() -match '(^|\s)[|>][-+0-9]*$') {
            $prefix = [regex]::Match($code, '^\s*(?:-\s+)*').Value
            $dash = $prefix.LastIndexOf('-')
            $state.BlockIndent = if ($dash -ge 0 -and $code.Substring($prefix.Length) -match '^[|>]') { $dash } else { $prefix.Length }
        }
    }
    , $comments
}

function Find-ScriptCommentProblem {
    param([object[]]$Lines, [string]$WholeFileRoot, [System.Collections.Generic.HashSet[string]]$Installed, [System.Collections.Generic.List[string]]$Unchecked)
    $findings = [System.Collections.Generic.List[object]]::new()
    $selected = @($Lines | Where-Object { $p = $_.File.Replace('\', '/'); $p -match $scriptPathPattern -and -not $Installed.Contains($p) })
    foreach ($group in ($selected | Group-Object -Property File)) {
        $fileLines = @($group.Group)
        $onDisk = if ($WholeFileRoot) { Join-Path $WholeFileRoot $group.Name } else { $null }
        $wholeFile = [bool]($onDisk -and (Test-Path -LiteralPath $onDisk -PathType Leaf))
        if ($wholeFile) {
            $n = 0
            $fileLines = @(Get-Content -LiteralPath $onDisk | ForEach-Object { $n++; [pscustomobject]@{ Line = $n; Text = $_ } })
        }
        $isYaml = $group.Name -match '\.ya?ml$'
        $comments = if ($isYaml) { Get-YamlComment -Lines $fileLines } else { Get-PowerShellComment -Lines $fileLines -WholeFile $wholeFile }
        if ($null -eq $comments) { $Unchecked.Add("$($group.Name) : the file does not parse"); continue }
        $addedAt = @{}
        foreach ($a in $group.Group) { if ($a.IsAdded) { $addedAt[[int]$a.Line] = $a.Text } }
        foreach ($c in $comments) {
            if (-not $addedAt.ContainsKey([int]$c.Line)) { continue }
            $problem = Get-ScriptCommentProblem -Text $c.Text.Trim() -Kind $c.Kind -IsYaml $isYaml
            if ($problem) { $findings.Add([pscustomobject]@{ File = $group.Name; Line = $c.Line; Text = $addedAt[[int]$c.Line]; Problem = $problem }) }
        }
    }
    $findings
}

function Get-ScriptDiff {
    if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
        return [pscustomobject]@{ Problem = 'git is not available, so the change could not be read'; Text = ''; Base = $null }
    }
    $base = git -C $RepoRoot merge-base $BaseRef HEAD 2>$null
    if ($LASTEXITCODE -ne 0 -or -not $base) {
        return [pscustomobject]@{ Problem = "no merge base with '$BaseRef', so the change could not be read"; Text = ''; Base = $null }
    }
    $baseCommit = ([string]@($base)[0]).Trim()
    # Quoted literals, because pwsh on Linux expands a wildcard held in a variable against the current folder.
    $diff = git -C $RepoRoot -c core.quotepath=off diff --unified=30 --no-color --no-ext-diff $baseCommit -- '*.ps1' '*.psm1' '*.psd1' '*.yml' '*.yaml' 2>$null
    if ($LASTEXITCODE -ne 0) {
        return [pscustomobject]@{ Problem = "git diff against $baseCommit failed"; Text = ''; Base = $baseCommit }
    }
    $text = ($diff -join "`n")
    $untracked = git -C $RepoRoot -c core.quotepath=off ls-files --others --exclude-standard -- '*.ps1' '*.psm1' '*.psd1' '*.yml' '*.yaml' 2>$null
    if ($LASTEXITCODE -ne 0) {
        return [pscustomobject]@{ Problem = 'git ls-files failed, so the new files could not be listed'; Text = ''; Base = $baseCommit }
    }
    foreach ($u in @($untracked | Where-Object { $_ })) {
        $content = @(Get-Content -LiteralPath (Join-Path $RepoRoot $u))
        $text += "`n--- /dev/null`n+++ b/$u`n@@ -0,0 +1,$($content.Count) @@`n" + (($content | ForEach-Object { "+$_" }) -join "`n")
    }
    return [pscustomobject]@{ Problem = $null; Text = $text; Base = $baseCommit }
}

function Invoke-ScriptCommentCheck {
    $installed = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $wholeFileRoot = $null
    if (-not $script:DiffTextGiven) {
        $read = Get-ScriptDiff
        if ($read.Problem) {
            Write-Host "Comment hygiene: $($read.Problem), so NOTHING WAS CHECKED." -ForegroundColor Yellow
            Write-Host 'FIX: Make the base branch available (git fetch origin main), or pass -BaseRef with a ref the clone has.' -ForegroundColor Yellow
            return 2
        }
        $list = Get-AiSdlcInstalledPath -RepoRoot $RepoRoot -Base $read.Base -WithHeadInstall
        if (-not $list.Readable) {
            Write-Host "Comment hygiene: the list of installed files could not be read ($($list.Reason)), so NOTHING WAS CHECKED." -ForegroundColor Yellow
            Write-Host 'FIX: Fetch the base branch (git fetch origin main), or pass -BaseRef with a commit that exists, then run this check again.' -ForegroundColor Yellow
            return 2
        }
        $installed = $list.Paths
        $wholeFileRoot = $RepoRoot
        $script:ScriptDiff = $read.Text
    }
    $lines = @(Get-CodeDiffLine -Diff $script:ScriptDiff)
    $unchecked = [System.Collections.Generic.List[string]]::new()
    $findings = @(Find-ScriptCommentProblem -Lines $lines -WholeFileRoot $wholeFileRoot -Installed $installed -Unchecked $unchecked)

    if ($findings.Count -gt 0) {
        Write-Host 'C10: the change adds comments to PowerShell or YAML files that are dead code, an open TODO without an issue key, or that name an AI tool.' -ForegroundColor Yellow
        Write-Host 'FIX: Delete commented-out code (git keeps the history). Give each TODO, FIXME or HACK an issue key such as #42, or do the work now. Remove the name of an AI tool; a comment says why the code is so (clause C10, .claude/skills/ai-sdlc-handbook/references/comments.md).' -ForegroundColor Yellow
        foreach ($f in $findings) { Write-Host ("  {0}:{1}  [{2}]  {3}" -f $f.File, $f.Line, $f.Problem, $f.Text.Trim()) }
        Write-Host ("Found {0} comment problem(s) in {1} file(s)." -f $findings.Count, @($findings | Select-Object -ExpandProperty File -Unique).Count) -ForegroundColor Yellow
    }
    if ($unchecked.Count -gt 0) {
        Write-Host 'Comment hygiene: the PowerShell parser reported errors, so NOTHING WAS CHECKED in these file(s):' -ForegroundColor Yellow
        foreach ($u in $unchecked) { Write-Host "  $u" }
        Write-Host 'FIX: Fix the syntax error that pwsh reports for each file named above, then run this check again.' -ForegroundColor Yellow
    }
    if ($findings.Count -gt 0) { return 1 }
    if ($unchecked.Count -gt 0) { return 2 }

    $checked = @($lines | Where-Object { $p = $_.File.Replace('\', '/'); $_.IsAdded -and $p -match $scriptPathPattern -and -not $installed.Contains($p) }).Count
    if ($checked -eq 0) {
        Write-Host 'Not applicable: the change adds no PowerShell or YAML line, so there is no comment to look for.'
        return 3
    }
    Write-Host ("Comment hygiene OK: {0} added PowerShell and YAML line(s) checked, no dead code, open TODO or AI tool name in a comment." -f $checked)
    return 0
}

if ($Language -eq 'YamlPowerShell') {
    $script:DiffTextGiven = $PSBoundParameters.ContainsKey('DiffText')
    $script:ScriptDiff = $DiffText
    exit (Invoke-ScriptCommentCheck)
}

if (-not $PSBoundParameters.ContainsKey('DiffText')) {
    $read = Get-CodeDiffText -RepoRoot $RepoRoot -BaseRef $BaseRef -ContextLines 30
    if ($read.Problem) {
        Write-Host "Comment hygiene: $($read.Problem), so NOTHING WAS CHECKED." -ForegroundColor Yellow
        Write-Host 'FIX: Make the base branch available (git fetch origin main), or pass -BaseRef with a ref the clone has.' -ForegroundColor Yellow
        exit 2
    }
    $DiffText = $read.Text
}

$lines = @(Get-CodeDiffLine -Diff $DiffText)
$findings = @(Find-CommentProblems -Lines $lines)

if ($findings.Count -gt 0) {
    Write-Host 'C10 violation: the change adds comments that are dead code, an open TODO without an issue key, or that name an AI tool.' -ForegroundColor Red
    Write-Host 'FIX: Delete commented-out code (git keeps the history). Give each TODO, FIXME or HACK an issue key such as #42, or do the work now. Remove the name of an AI tool; a comment says why the code is so (clause C10, .claude/skills/ai-sdlc-handbook/references/comments.md).' -ForegroundColor Red
    foreach ($f in $findings) { Write-Host ("  {0}:{1}  [{2}]  {3}" -f $f.File, $f.Line, $f.Problem, $f.Text.Trim()) }
    $files = ($findings | Select-Object -ExpandProperty File -Unique).Count
    Write-Host ("Found {0} comment problem(s) in {1} file(s)." -f $findings.Count, $files) -ForegroundColor Red
    exit 1
}

$checked = @($lines | Where-Object { $_.IsAdded -and (Test-CodeDiffPath -Path $_.File) }).Count
Write-Host ("Comment hygiene OK: {0} added C# and Razor line(s) checked, no dead code, open TODO or AI tool name in a comment." -f $checked)
exit 0
