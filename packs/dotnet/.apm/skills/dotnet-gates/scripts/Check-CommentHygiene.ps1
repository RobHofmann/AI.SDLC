#Requires -Version 7
<#
.SYNOPSIS
    Gate: a change adds no dead or noisy comment to C# or Razor code (clause C10).
.DESCRIPTION
    Code is documented, and a comment says why, not what. Three kinds of comment never help, so this
    gate blocks them in the lines a change adds:
      - commented-out code: a comment whose text reads as a C# statement or declaration. It ends with
        ;, { or }, or it starts like code: var x =, return x(, if (, foreach (, public int X {, [Fact];
      - a TODO, FIXME or HACK without an issue key, such as #42 (tracker.keyPattern in aisdlc.json);
      - a comment that names an AI tool: Claude, Copilot, ChatGPT, GPT, "generated by" or "AI-generated".
    A /// doc comment is not read as code, but the other two checks apply to it. The // Arrange, // Act
    and // Assert test markers pass. See the comments page of the ai-sdlc-handbook skill
    (.claude/skills/ai-sdlc-handbook/references/comments.md).

    The gate reads the change, not the tree: only ADDED lines are checked, so old comments do not fail
    anyone. The diff carries 30 lines of context, and those lines are read too, so an added line inside
    a raw string or a /* */ block that opened just before the change is judged by what it really is.
    It diffs the working tree against the merge base of -BaseRef and HEAD, and it reads untracked .cs
    and .razor files whole.

    What counts as a comment:
      C#     a line that starts with //, /// or /*, a line inside a /* */ block, and a trailing // or
             /* after code. String and character literals are removed first, including raw ("""),
             verbatim (@", $@", @$") and interpolated strings, so a URL inside a string is not a comment.
      Razor  the C# forms above at the start of a line, a @* *@ block and an <!-- --> block.
    Known limit: a string or a block that opened more than 30 lines before the change is not seen.
    Generated files (*.Designer.cs, *.g.cs, *.g.i.cs and anything under bin/ or obj/) are skipped.

    Exit codes follow Invoke-Gate.ps1: 0 checked and clean, 1 a finding, 2 the change could not be
    computed (no git, no repository, or no base ref), so nothing was checked.
.PARAMETER RepoRoot
    Repository root. Defaults to the folder that holds aisdlc.json, found from this script.
.PARAMETER BaseRef
    The ref the change is measured against. Defaults to origin/main. The pull request build passes
    HEAD^1, the target branch side of the merge commit.
.PARAMETER DiffText
    A unified diff to read instead of asking git. Used by the tests.
.EXAMPLE
    pwsh .claude/skills/dotnet-gates/scripts/Check-CommentHygiene.ps1
.EXAMPLE
    pwsh .claude/skills/dotnet-gates/scripts/Check-CommentHygiene.ps1 -BaseRef HEAD^1
#>
[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$BaseRef = 'origin/main',
    [string]$DiffText
)

$aiSdlcGates = Join-Path $PSScriptRoot '..' '..' 'ai-sdlc-gates' 'scripts'
if (-not (Test-Path -LiteralPath $aiSdlcGates)) { $aiSdlcGates = Join-Path $PSScriptRoot '..' '..' '..' '..' '..' '..' 'core' '.apm' 'skills' 'ai-sdlc-gates' 'scripts' }
Import-Module (Join-Path $aiSdlcGates 'AiSdlcConfig.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'CodeDiff.psm1') -Force
if (-not $RepoRoot) { $RepoRoot = Find-AiSdlcRepoRoot -StartPath $PSScriptRoot }

$ErrorActionPreference = 'Stop'

$testMarker = '^//\s*(Arrange|Act|Assert)(\s*(&|and|/|,)\s*(Arrange|Act|Assert))*\s*$'
$literalPattern = '\$*(?<q>"{3,})(?:(?!\k<q>).)*\k<q>|(?:\$@|@\$|@)"(?:[^"]|"")*"|\$"(?:[^"\\{}]|\\.|\{\{|\}\}|\{(?:[^{}"]|"(?:[^"\\]|\\.)*")*\})*"|\$?"(?:[^"\\]|\\.)*"|''(?:[^''\\]|\\.)'''
$aiToolPattern = '(?i)\b(claude|copilot|chatgpt|gpt)\b|\bgenerated\s+by\b|\bai[- ]generated\b'
$todoPattern = '(?-i)\b(TODO|FIXME|HACK)\b'
$codeStartPatterns = @(
    '^(if|for|foreach|while|switch|using|lock|catch)\s*\(',
    '^var\s+\w+\s*=',
    '^(return|throw|await|yield\s+return)\s+(new\s+)?[\w.<>\[\]]+\s*[\(;]',
    '^(public|private|protected|internal)\s+([\w<>\[\],?]+\s+)+\w+\s*(\(|\{|=|;)',
    '^\[\w+(\(.*\))?\]$'
)

function Remove-Literals {
    param([string]$Line)
    [regex]::Replace($Line, $literalPattern, '""')
}

function Split-OpenString {
    param([string]$Code)
    $raw = [regex]::Match($Code, '(?<q>"{3,})\s*$')
    if ($raw.Success) { return [pscustomobject]@{ Before = $Code.Substring(0, $raw.Index); End = $raw.Groups['q'].Value } }
    $verbatim = [regex]::Match($Code, '(?:\$@|@\$|@)"')
    if ($verbatim.Success) { return [pscustomobject]@{ Before = $Code.Substring(0, $verbatim.Index); End = 'verbatim' } }
    return [pscustomobject]@{ Before = $Code; End = $null }
}

function Close-OpenString {
    param([string]$Text, [string]$End)
    $close = if ($End -eq 'verbatim') { [regex]::Match(($Text -replace '""', '__'), '"') } else { [regex]::Match($Text, [regex]::Escape($End)) }
    if (-not $close.Success) { return $null }
    return $Text.Substring($close.Index + $close.Length).Trim()
}

function Get-TrailingComment {
    param([string]$Text, [hashtable]$State)
    $open = Split-OpenString (Remove-Literals $Text)
    $State.StringEnd = $open.End
    $trailing = [regex]::Match($open.Before, '//|/\*')
    if (-not $trailing.Success) { return $null }
    $rest = $open.Before.Substring($trailing.Index)
    if ($trailing.Value -eq '/*' -and -not $rest.Substring(2).Contains('*/')) { $State.BlockEnd = '*/' }
    return $rest
}

function Get-LeadingComment {
    param([string]$Text, [bool]$IsRazor, [hashtable]$State)
    if ($IsRazor) {
        $razorOpen = [regex]::Match($Text, '@\*|<!--')
        if ($razorOpen.Success) {
            $close = if ($razorOpen.Value -eq '@*') { '*@' } else { '-->' }
            if (-not $Text.Substring($razorOpen.Index + $razorOpen.Length).Contains($close)) { $State.BlockEnd = $close }
            return $Text.Substring($razorOpen.Index)
        }
    }
    if ($Text.StartsWith('//')) { return $Text }
    if ($Text.StartsWith('/*')) {
        if (-not $Text.Substring(2).Contains('*/')) { $State.BlockEnd = '*/' }
        return $Text
    }
    return $null
}

function Get-CommentText {
    param([string]$Text, [bool]$IsRazor, [hashtable]$State)
    if ($State.StringEnd) {
        $rest = Close-OpenString -Text $Text -End $State.StringEnd
        if ($null -eq $rest) { return $null }
        $State.StringEnd = $null
        if ($rest -eq '') { return $null }
        return (Get-TrailingComment -Text $rest -State $State)
    }
    if ($State.BlockEnd) {
        if ($Text.Contains($State.BlockEnd)) { $State.BlockEnd = $null }
        return $Text
    }
    if ($Text -eq '') { return $null }
    $leading = Get-LeadingComment -Text $Text -IsRazor $IsRazor -State $State
    if ($null -ne $leading) { return $leading }
    if ($IsRazor) { return $null }
    return (Get-TrailingComment -Text $Text -State $State)
}

function Get-CommentProblem {
    param([string]$Comment)
    if ($Comment -match $testMarker) { return $null }
    if ($Comment -match $aiToolPattern) { return 'names an AI tool' }
    if ($Comment -cmatch $todoPattern -and -not (Get-AiSdlcStoryKey -Text $Comment -RepoRoot $RepoRoot)) { return 'TODO without an issue key' }
    if ($Comment.StartsWith('///')) { return $null }
    $body = ($Comment -replace '^\s*(/{2,}|/\*+|\*+|@\*|<!--)', '' -replace '(\*+/|\*@|-->)\s*$', '').Trim()
    if ($body -eq '') { return $null }
    if ($body -match '[;{}]$' -and $body -notmatch '\S\{[\w:]+\}$') { return 'commented-out code' }
    foreach ($p in $codeStartPatterns) { if ($body -cmatch $p) { return 'commented-out code' } }
    return $null
}

function Find-CommentProblems {
    param([object[]]$Lines)
    $findings = [System.Collections.Generic.List[object]]::new()
    $state = @{ BlockEnd = $null; StringEnd = $null }
    $prev = $null
    foreach ($l in $Lines) {
        $path = $l.File.Replace('\', '/')
        if (-not (Test-CodeDiffPath -Path $path)) { continue }
        if ($prev -and ($prev.File -ne $l.File -or $prev.Line + 1 -ne $l.Line)) { $state.BlockEnd = $null; $state.StringEnd = $null }
        $prev = $l
        $comment = Get-CommentText -Text $l.Text.Trim() -IsRazor $path.EndsWith('.razor') -State $state
        if ($null -eq $comment -or -not $l.IsAdded) { continue }
        $problem = Get-CommentProblem -Comment $comment
        if ($problem) { $findings.Add([pscustomobject]@{ File = $l.File; Line = $l.Line; Text = $l.Text; Problem = $problem }) }
    }
    $findings
}

if (-not $PSBoundParameters.ContainsKey('DiffText')) {
    $read = Get-CodeDiffText -RepoRoot $RepoRoot -BaseRef $BaseRef -ContextLines 30
    if ($read.Problem) {
        Write-Host "Comment hygiene: $($read.Problem), so NOTHING WAS CHECKED." -ForegroundColor Yellow
        exit 2
    }
    $DiffText = $read.Text
}

$lines = @(Get-CodeDiffLine -Diff $DiffText)
$findings = @(Find-CommentProblems -Lines $lines)

if ($findings.Count -gt 0) {
    Write-Host 'C10 violation: the change adds comments that are dead code, an open TODO without an issue key, or that name an AI tool.' -ForegroundColor Red
    Write-Host 'FIX: Delete commented-out code (git keeps the history). Give each TODO, FIXME or HACK an issue key such as #42, or do the work now. Remove the name of an AI tool; a comment says why the code is so (clause C10, .claude/skills/ai-sdlc-handbook/references/comments.md).' -ForegroundColor Red
    foreach ($f in $findings) { Write-Host ("  {0}:{1}  [{2}]  {3}" -f $f.File, $f.Line, $f.Problem, $f.Text.Trim()) }
    $files = ($findings | Select-Object -ExpandProperty File -Unique).Count
    Write-Host ("Found {0} comment problem(s) in {1} file(s)." -f $findings.Count, $files) -ForegroundColor Red
    exit 1
}

$checked = @($lines | Where-Object { $_.IsAdded -and (Test-CodeDiffPath -Path $_.File) }).Count
Write-Host ("Comment hygiene OK: {0} added C# and Razor line(s) checked, no dead code, open TODO or AI tool name in a comment." -f $checked)
exit 0
